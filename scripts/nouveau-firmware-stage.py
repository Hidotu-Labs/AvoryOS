#!/usr/bin/env python3
"""Stage the reviewed AD106 GSP closure without changing the AMD bundle."""
from pathlib import Path
import argparse, fcntl, hashlib, json, os, shutil, tempfile, zlib
ROOT = Path(__file__).resolve().parents[1]

def stage(source, output, lock):
    spec = json.loads(lock.read_text())['selected']['firmware']
    output = output.absolute()
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.is_symlink(): raise RuntimeError('firmware output must not be a symlink')
    with (output.parent/'.firmware-stage.lock').open('a') as guard:
        fcntl.flock(guard, fcntl.LOCK_EX | fcntl.LOCK_NB)
        temp = Path(tempfile.mkdtemp(prefix='.firmware-', dir=output.parent))
        backup = output.with_name('.firmware-backup')
        try:
            rows = []
            for entry in spec['files']:
                name = entry['request']
                for relative in (name, entry['canonical_source']):
                    path = source/relative
                    if path.is_file(): break
                else: raise RuntimeError(f'missing pinned firmware: {name}')
                data = path.read_bytes()
                if len(data) != entry['size'] or hashlib.sha256(data).hexdigest() != entry['sha256']:
                    raise RuntimeError(f'firmware hash/size mismatch: {name}')
                dest = temp/'lib/firmware'/name
                dest.parent.mkdir(parents=True, exist_ok=True); dest.write_bytes(data)
                rows.append(dict(entry, crc32=zlib.crc32(data)))
            license = source/spec['license']
            if not license.is_file(): raise RuntimeError(f'missing redistribution notice: {license}')
            notice = temp/'lib/firmware'/spec['license']
            notice.parent.mkdir(parents=True, exist_ok=True); shutil.copyfile(license, notice)
            (temp/'manifest.json').write_text(json.dumps(dict(ref=spec['ref'], commit=spec['commit'],
                gsp_interface=spec['gsp_interface'], files=rows,
                license_sha256=hashlib.sha256(license.read_bytes()).hexdigest()), indent=2)+'\n')
            header = ['/* Generated by nouveau-firmware-stage.py. */', '#ifndef KPI_NOUVEAU_FW_MANIFEST_H',
                      '#define KPI_NOUVEAU_FW_MANIFEST_H',
                      'static const struct { const char *name; unsigned int size, crc32; } kpi_nouveau_fw_manifest[] = {']
            header += [f'  {{"{r["request"]}", {r["size"]}u, 0x{r["crc32"]:08x}u}},' for r in rows]
            header += ['};', f'#define KPI_NOUVEAU_FW_COUNT {len(rows)}u', '#endif', '']
            (temp/'kpi_nouveau_fw_manifest.h').write_text('\n'.join(header))
            if backup.exists(): raise RuntimeError(f'unresolved staging backup: {backup}')
            if output.exists(): output.rename(backup)
            try: temp.rename(output)
            except BaseException:
                if backup.exists(): backup.rename(output)
                raise
            if backup.exists(): shutil.rmtree(backup)
        finally:
            if temp.exists(): shutil.rmtree(temp)
    return rows

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'build/nouveau-c0/firmware')
    parser.add_argument('--output', type=Path, default=ROOT/'build/nouveau/firmware')
    parser.add_argument('--interface', choices=('570.144',))
    args = parser.parse_args()
    if args.interface:
        source = ROOT/'build/firmware/lib/firmware'
        hashes = {name: digest for digest, name in
                  (line.split() for line in (ROOT/'scripts/linux/firmware-sha256-20260916.txt').read_text().splitlines()
                   if line.strip() and not line.startswith('#'))}
        names = [f'nvidia/ad106/gsp/{name}-{args.interface}.bin' for name in
                 ('gsp', 'bootloader', 'booter_load', 'booter_unload')]
        notice = 'LICENSES/LICENCE.nvidia'
        if any(not (source/name).is_file() for name in names+[notice]):
            import subprocess
            subprocess.run(['bash', str(ROOT/'scripts/linux-firmware-install.sh')], check=True)
        spec = {'ref': 'linux-firmware 20260916', 'commit': '20260916',
                'gsp_interface': args.interface,
                'files': [dict(request=name, canonical_source=name,
                               size=(source/name).stat().st_size, sha256=hashes[name])
                          for name in names], 'license': notice}
        lock = ROOT/'build/nouveau-618/firmware-profile.json'
        lock.parent.mkdir(parents=True, exist_ok=True)
        lock.write_text(json.dumps({'selected': {'firmware': spec}}))
        rows = stage(source, args.output, lock)
    else:
        rows = stage(args.source, args.output, ROOT/'docs/nouveau/c0-lock.json')
    print(f'Staged {len(rows)} pinned AD106 files ({sum(r["size"] for r in rows):,} bytes) and NVIDIA notice in {args.output}')

if __name__ == '__main__':
    try: main()
    except (OSError, RuntimeError, ValueError) as error: raise SystemExit(str(error))
